#!/usr/bin/env bash
# ЛР4: предварительная настройка сервера под стенд «Restaurant Booking».
#
# Скрипт идемпотентный и «бережный» к общему серверу:
#   • только доустанавливает недостающие пакеты (apt-get install --no-upgrade), ничего не обновляет;
#   • Docker не переустанавливает и не перезапускает, если он уже есть;
#   • не меняет ufw / sshd / чужие контейнеры; всё своё — в /opt/rb-sem2 и в docker-ресурсах с префиксом rb-.
#
# Запуск: sudo bash server-setup.sh
set -euo pipefail

ROOT=/opt/rb-sem2
REPO_URL=${REPO_URL:-https://github.com/cicada-pops/itmo-backend-sem2.git}
BUILDER=rb-builder

log() { printf '\033[1;34m[setup]\033[0m %s\n' "$*"; }

[[ $EUID -eq 0 ]] || { echo "run as root" >&2; exit 1; }

# 1. Системные зависимости (только недостающие)
missing=()
for pair in git:git curl:curl jq:jq openssl:openssl rsync:rsync; do
  bin=${pair%%:*}; pkg=${pair##*:}
  command -v "$bin" >/dev/null 2>&1 || missing+=("$pkg")
done
if ((${#missing[@]})); then
  log "installing: ${missing[*]}"
  apt-get update -qq
  DEBIAN_FRONTEND=noninteractive apt-get install -y -qq --no-install-recommends --no-upgrade "${missing[@]}"
else
  log "system packages: all present (git, curl, jq, openssl, rsync)"
fi

# 2. Docker Engine + Compose plugin
if ! command -v docker >/dev/null 2>&1; then
  log "docker not found -> installing from the official repository"
  install -m 0755 -d /etc/apt/keyrings
  curl -fsSL https://download.docker.com/linux/ubuntu/gpg -o /etc/apt/keyrings/docker.asc
  echo "deb [arch=$(dpkg --print-architecture) signed-by=/etc/apt/keyrings/docker.asc] https://download.docker.com/linux/ubuntu $(. /etc/os-release && echo "$VERSION_CODENAME") stable" \
    > /etc/apt/sources.list.d/docker.list
  apt-get update -qq
  DEBIAN_FRONTEND=noninteractive apt-get install -y -qq docker-ce docker-ce-cli containerd.io docker-buildx-plugin docker-compose-plugin
  systemctl enable --now docker
fi
log "$(docker --version)"
log "$(docker compose version)"
log "$(docker buildx version | cut -d' ' -f1-2)"

# 3. Каталоги стенда
# 0711: в корень можно «пройти» (нужно пользователю CI для запуска bin/deploy-gate.sh), но не листать
install -d -m 0711 "$ROOT"
install -d -m 0750 "$ROOT/app"
install -d -m 0755 "$ROOT/bin"
install -d -m 0755 "$ROOT/edge" "$ROOT/edge/conf.d" "$ROOT/edge/html"
log "directories under $ROOT ready"

# 4. Общая docker-сеть: edge-nginx <-> gateway (позже: Grafana, k3d)
docker network inspect rb-edge >/dev/null 2>&1 || docker network create rb-edge >/dev/null
log "docker network rb-edge ready"

# 5. Отдельный сборщик образов с ограничениями (1 CPU из ядер 2-3, 1.5 ГБ RAM),
#    чтобы сборка не отнимала ресурсы у соседнего проекта
if ! docker buildx inspect "$BUILDER" >/dev/null 2>&1; then
  docker buildx create --name "$BUILDER" --driver docker-container \
    --driver-opt '"cpuset-cpus=2,3"' --driver-opt cpu-quota=100000 --driver-opt cpu-period=100000 \
    --driver-opt memory=1536m --driver-opt default-load=true >/dev/null
fi
log "buildx builder $BUILDER ready (cpuset 2-3, 1 CPU, 1.5 GiB)"

# 6. Исходники (публичный репозиторий, только чтение)
if [[ -d "$ROOT/src/.git" ]]; then
  git -C "$ROOT/src" fetch -q origin && git -C "$ROOT/src" checkout -q --detach origin/main
else
  git clone -q "$REPO_URL" "$ROOT/src"
fi
log "sources: $(git -C "$ROOT/src" log -1 --format='%h %s')"

# 7. Секреты генерируются на сервере и никогда не попадают в git
if [[ ! -f "$ROOT/app/.env" ]]; then
  umask 077
  cat > "$ROOT/app/.env" <<ENV
# generated by server-setup.sh at $(date -Is)
JWT_SECRET=$(openssl rand -hex 32)
JWT_EXPIRES_IN=7d
INTERNAL_API_KEY=$(openssl rand -hex 24)
RABBITMQ_USER=rb
RABBITMQ_PASS=$(openssl rand -hex 16)
IMAGE_PREFIX=local/rb
IMAGE_TAG=latest
ENV
  log "secrets generated -> $ROOT/app/.env (0600)"
else
  log "secrets already exist -> $ROOT/app/.env (kept)"
fi

log "done"
